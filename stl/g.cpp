#include <bits/stdc++.h>

using namespace std;

signed main() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, k, p;
    cin >> n >> k >> p;
    vector<int> r(p);
    map<int, set<int>> f; // табица в которой ключ - номер машинки, ззначение - множество индексов с ее появлением

    for (size_t i = 0; i < r.size(); ++i) {
        cin >> r[i];
        f[r[i]].insert(i); // ззаполняем ножество появлений индексов для текущей машинки
    }

    //ответ
    int total_ops = 0;

    set<pair<int, int>> s; // множество с парами (next_, номер машинки)
    // жто множество машинок отсортировано по певой цифре пары по умолчанию, самая последняя пара - машика которая понадобится долше всех
    vector<int> next_(n+1); // индекс следующего появления для каждой машинки, n+1 потому что машинки имеют нумерацию с 1 а не 0
    set<int> w; // множество машинок на полу
    for (size_t i = 0; i < r.size(); ++i) { // идем по запросам
        int cur = r[i]; // текущая машинка
        f[cur].erase(f[cur].begin()); // удалем текущий индекс из таблицы  индексами бдуущих появлений
        if (w.count(cur)) s.erase({next_[cur], cur}); 
        if (f[cur].size() > 0) {
            next_[cur] = *f[cur].begin(); // если для текущей машинки множество появлений еще не пусто то ее слеющее появление это начало множества
        }
        else {
            next_[cur] = p; // иначе она больше не понадобится
        }
        if (w.find(cur) == w.end()) { // если машинки нет на полу
            if (w.size() < k) { // если на полу еще есть место
                w.insert(cur); // скидываем на пол машинку
                s.insert({next_[cur], cur});
            }
            else  { // если на полу больше нет места
                auto it = prev(s.end()); 
                int victim = it->second;
                s.erase(it); 
                w.erase(victim); //убираем с пола машинку
                w.insert(cur); // добавляем на пол машинку
                s.insert({next_[cur], cur});
            }
            total_ops++; //придется сделать еще одну операцию
        }
        else {
            // но если машинка на полу то обновляем ее 
            // потому что тут хранится индекс когда она понадобится. 
            // смысл в том что если машинку попросили, то надо обновить ее следующее появление
            s.insert({next_[cur], cur});
        }
    }
    cout << total_ops << '\n';
}
